async (page) => {
    const assert = (value, message) => { if (!value) throw new Error(message) }
    const waitIdle = () => page.locator('[data-tricks-replay-root][aria-busy="false"]').waitFor()
    await page.unrouteAll()
    await page.setViewportSize({width:1440,height:1000})
    await page.goto('http://localhost:3005/limited/tricks')
    await page.getByRole('button',{name:'リプレイモード',exact:true}).click()
    await waitIdle()
    const slider=page.getByRole('slider',{name:'リプレイ時点'})
    const seek=async index => {
        await slider.evaluate((el,index)=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,index);el.dispatchEvent(new Event('input',{bubbles:true}))},index)
        await slider.dispatchEvent('pointerup')
        await waitIdle()
    }
    assert(await page.locator('[data-tricks-replay-toggle]').evaluate(el=>getComputedStyle(el).color)==='rgb(33, 150, 243)','Active replay icon blue')
    assert(!(await page.locator('[data-tricks-replay-root]').textContent()).includes('リプレイ：閲覧専用'),'Read-only label removed')
    assert(!(await page.locator('[data-tricks-replay-current-time]').textContent()).includes('表示中'),'Time prefix removed')
    const panel = await page.locator('[data-tricks-replay-seekbar]').evaluate(el=>{const r=el.getBoundingClientRect(),s=getComputedStyle(el);return {left:r.left,right:innerWidth-r.right,bottom:innerHeight-r.bottom,radius:s.borderRadius,background:s.backgroundColor}})
    assert(panel.left>=5&&panel.right>=5&&panel.bottom>=5&&panel.radius==='12px','Panel margin and corners')
    assert(panel.background.includes('0.9'),'Panel opacity 90%')
    await seek(76)
    const raw=await(await page.request.get('http://localhost:3005/api/server/tricks/replay/261009/snapshot?checkpoint=76')).json()
    const state=raw.data??raw
    const user=state.players.find(user=>state.hands_by_player[user.name]?.length)
    const block=page.locator(`[data-tricks-player="${user.name}"]`)
    await block.click()
    assert(await page.locator('[data-tricks-replay-card-type="hand"]').count()>0,'User hand opens')
    assert(await page.locator('[data-tricks-replay-selected-user]').count()===0,'Hand label removed')
    await block.click()
    await page.waitForTimeout(300)
    assert(await page.locator('[data-tricks-replay-card-type="hand"]').count()===0,'Second click hides hand')
    const card=state.field.find(card=>state.rankings_by_card[card.id]?.length)
    await page.locator(`[data-tricks-replay-card="${card.event_card_id}"] button`).click()
    const modal=page.locator('.tricks-replay-detail-panel')
    const appearance=await modal.evaluate(el=>{const r=el.getBoundingClientRect(),s=getComputedStyle(el);return {background:s.backgroundColor,radius:s.borderRadius,overflow:s.overflow,bottom:r.bottom,top:r.top,recordColor:getComputedStyle(el.querySelector('.record-container')).color}})
    assert(appearance.background!=='rgba(0, 0, 0, 0)'&&appearance.radius==='14px'&&appearance.overflow==='hidden','Ranking modal has opaque styled container')
    assert(appearance.top>=0&&appearance.bottom<911,'Ranking modal inside viewport above seek bar')
    await page.screenshot({path:'next/pages/limited/tricks/output/playwright/tricks-replay-controls-modal.png'})
    await page.getByRole('button',{name:'閉じる',exact:true}).click()
    let reads=0,writes=0
    const listener=req=>{if(req.url().includes('/tricks/replay/')&&req.url().includes('/snapshots?'))reads++;if(req.url().includes('/tricks/')&&req.method()==='POST')writes++}
    page.on('request',listener)
    await slider.evaluate(el=>{
        window.replayTicks=[]
        window.replayObserver=new MutationObserver(()=>{const last=window.replayTicks.at(-1);if(last?.index!==Number(el.value))window.replayTicks.push({index:Number(el.value),at:performance.now()})})
        window.replayObserver.observe(el,{attributes:true,attributeFilter:['value']})
    })
    const play=page.getByRole('button',{name:'リプレイを再生',exact:true})
    const pause=page.getByRole('button',{name:'リプレイを一時停止',exact:true})
    await play.click()
    await page.waitForFunction(()=>window.replayTicks.length>=3)
    const x1=await page.evaluate(()=>window.replayTicks.slice(0,3).map(t=>t.at))
    assert(x1[2]-x1[1]>750&&x1[2]-x1[1]<1300,'x1 advances every second')
    await page.getByRole('combobox',{name:'リプレイ再生速度'}).selectOption('2')
    await page.evaluate(()=>{window.replayTicks=[]})
    await page.waitForFunction(()=>window.replayTicks.length>=3)
    const x2=await page.evaluate(()=>window.replayTicks.slice(0,3).map(t=>t.at))
    assert(x2[2]-x2[1]>350&&x2[2]-x2[1]<750,'x2 speed changes during playback')
    await page.getByRole('combobox',{name:'リプレイ再生速度'}).selectOption('4')
    await page.evaluate(()=>{window.replayTicks=[]})
    await page.waitForFunction(()=>window.replayTicks.length>=5)
    const x4=await page.evaluate(()=>window.replayTicks.slice(0,5))
    assert(x4[4].at-x4[3].at>150&&x4[4].at-x4[3].at<450,'x4 advances every quarter second')
    assert(x4.every((tick,index)=>!index||tick.index===x4[index-1].index+1),'No skipped snapshots')
    await pause.click()
    const paused=await slider.inputValue()
    await page.waitForTimeout(1200)
    assert(await slider.inputValue()===paused,'Pause freezes position')
    assert(reads<=4,'Batch prefetch reduces request frequency')
    await seek(191)
    await play.click()
    await page.waitForFunction(()=>document.querySelector('input[aria-label="リプレイ時点"]').value==='192')
    await page.getByRole('button',{name:'リプレイを再生',exact:true}).waitFor()
    assert(await play.isDisabled(),'Playback stops at final snapshot')
    await page.getByRole('combobox',{name:'リプレイ粒度'}).selectOption('frame')
    await waitIdle()
    await seek(0)
    await page.route('**/tricks/replay/261009/snapshots?**',async route=>{await new Promise(resolve=>setTimeout(resolve,1000));await route.continue()})
    await play.click()
    await page.waitForTimeout(350)
    await pause.click()
    const halted=await slider.inputValue()
    await page.waitForTimeout(1300)
    assert(await slider.inputValue()===halted,'Pause cancels pending fetch')
    await page.unrouteAll()
    await page.route('**/tricks/replay/261009/snapshots?**',async route=>{await new Promise(resolve=>setTimeout(resolve,700));await route.continue()})
    await page.evaluate(()=>{window.replayTicks=[]})
    await play.click()
    await page.waitForFunction(()=>window.replayTicks.length>=3)
    await pause.click()
    const logTicks=await page.evaluate(()=>window.replayTicks.slice(0,3))
    assert(logTicks.every((tick,index)=>!index||tick.index===logTicks[index-1].index+1),'Log playback advances one log per frame')
    assert(logTicks[1].at-logTicks[0].at>=200,'Delayed response does not cause immediate catch-up frame')
    await page.unrouteAll()
    await page.evaluate(()=>window.replayObserver.disconnect())
    await page.setViewportSize({width:390,height:844})
    const tooltip=await page.locator('[data-tricks-replay-time]').boundingBox()
    assert(tooltip.x>=0&&tooltip.x+tooltip.width<=390,'Mobile timestamp inside viewport')
    await page.screenshot({path:'next/pages/limited/tricks/output/playwright/tricks-replay-controls-mobile.png'})
    await page.setViewportSize({width:1440,height:1000})
    await page.getByRole('button',{name:'リプレイを終了',exact:true}).click()
    assert(writes===0,'No mutation requests')
    page.off('request',listener)
    return {checks:25,logFrameInterval:Math.round(logTicks[1].at-logTicks[0].at),x1Interval:Math.round(x1[2]-x1[1]),x2Interval:Math.round(x2[2]-x2[1]),x4Interval:Math.round(x4[4].at-x4[3].at),batchReads:reads,writes,panel,appearance}
}
