async (page) => {
    const assert = (value, message) => { if (!value) throw new Error(message) }
    const names = Array.from({length: 8}, (_, i) => `codex_dummy_251227_${String(i + 1).padStart(2, '0')}`)
    await page.setViewportSize({width: 1440, height: 1000})
    await page.goto('http://localhost:3005/limited/trick?event_id=251227')
    await page.locator('canvas').waitFor()
    await page.waitForFunction(() => document.querySelectorAll('[data-tricks-player]').length === 15)
    const response = await page.request.get('http://localhost:3005/api/server/tricks/state?event_id=251227')
    assert(response.ok(), '実APIの状態取得')
    const payload = await response.json()
    const state = payload.data || payload
    assert(state.tournament.event_id === 251227, '指定大会')
    assert(names.every(name => state.players.some(player => player.name === name)), 'ダミー8人の表示データ')
    const cards = state.field.filter(card => names.slice(0, 7).includes(card.taker))
    assert(cards.length === 7 && cards.every(card => card.stack_count === 3 && card.stage_id > 0), '7人の切り札と3枚スタック')
    assert(new Set(cards.map(card => card.stage_id)).size === 7, 'ステージID重複なし')
    assert(state.players.filter(player => names.slice(0, 7).includes(player.name)).every(player => player.card_count === 0 && player.take_count === 1), 'テイク後の手札と回数')
    assert(state.players.find(player => player.name === names[7]).take_count === 0, '8人目は参加のみ')
    for (const name of names) assert(await page.locator(`[data-tricks-player="${name}"]`).count() === 1, 'プレイヤー重複なし')
    await page.getByRole('button', {name: '観戦する', exact: true}).click()
    await page.waitForTimeout(300)
    const first = page.locator('.tricks-dom-card-field').first()
    await first.waitFor()
    const before = await first.boundingBox()
    await page.mouse.move(280, 220)
    await page.mouse.wheel(0, 200)
    await page.waitForTimeout(250)
    assert((await first.boundingBox()).y < before.y, '切り札が実際にスクロールする')
    await page.mouse.wheel(0, -200)
    await page.waitForTimeout(250)
    assert((await first.boundingBox()).y === before.y, '切り札スクロール復帰')
    await page.screenshot({path: 'output/playwright/tricks-251227-live.png'})
    const baseline = await page.evaluate(() => ({...window.__TRICKS_RENDER_METRICS__}))
    await page.waitForTimeout(1200)
    const metrics = await page.evaluate(() => ({...window.__TRICKS_RENDER_METRICS__}))
    assert(metrics.phaserLoopSleeping && metrics.activeRaf === 0 && metrics.activeTimers === 0 && metrics.phaserRenderCount === baseline.phaserRenderCount, 'Canvas静止・タイマー残留なし')
    return {eventId: 251227, players: state.players.length, dummyPlayers: 8, dummyField: cards.length, totalField: state.field.length, deck: state.deck_count, metrics}
}
