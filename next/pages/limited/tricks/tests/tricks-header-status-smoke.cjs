async (page) => {
    let checks=0
    const assert=(value,message)=>{if(!value)throw new Error(message);checks++}
    await page.unrouteAll()
    await page.setViewportSize({width:1440,height:1000})
    await page.goto('http://localhost:3005/limited/tricks')
    const results=page.getByTestId('tricks-collected-results')
    await results.waitFor()
    const verifyResults=async()=>{
        await page.waitForTimeout(350)
        const header=await page.locator('[data-tricks-header-scroll]').boundingBox()
        const box=await results.boundingBox()
        assert(box.y>=header.y+header.height&&box.y<=Math.max(174,Math.ceil(header.y+header.height)),'Result covers field from below protected player information')
        assert(box.x===0&&Math.abs(box.width-(await page.viewportSize()).width)<1&&Math.abs(box.y+box.height-(await page.viewportSize()).height)<1,'Results cover full remaining viewport')
        const player=page.locator('[data-tricks-player]').first()
        assert(await player.isVisible(),'Player block visible')
        assert(await player.evaluate(el=>{const r=el.getBoundingClientRect();const hit=document.elementFromPoint(r.x+r.width/2,r.y+20);return el.contains(hit)}),'Result does not cover player block')
        const covered=await results.evaluate(el=>{const r=el.getBoundingClientRect();return [[1,r.y+1],[innerWidth-1,r.y+1],[1,innerHeight-1],[innerWidth-1,innerHeight-1],[innerWidth/2,innerHeight-2]].every(([x,y])=>el.contains(document.elementFromPoint(x,y)) || Boolean(document.elementFromPoint(x,y)?.closest("[data-tricks-log-wrapper]")))})
        assert(covered,'Field-area corners covered, with log controls above results')
    }
    await verifyResults()
    await page.getByRole('button',{name:'観戦モード',exact:true}).click()
    await page.getByRole('link',{name:'観戦モードを解除',exact:true}).waitFor()
    assert((await page.locator('[data-tricks-header-status]').textContent()).includes('観戦モードで表示中（解除）'),'Spectator status in header')
    await verifyResults()
    await page.setViewportSize({width:1024,height:1000})
    await verifyResults()
    await page.screenshot({path:'next/pages/limited/tricks/output/playwright/tricks-results-cover-1024.png'})
    await page.getByRole('link',{name:'観戦モードを解除',exact:true}).click()
    assert(await page.getByRole('button',{name:'観戦モード',exact:true}).getAttribute('aria-pressed')==='false','Spectator exit link')
    await page.setViewportSize({width:1440,height:1000})
    let release
    const gate=new Promise(resolve=>{release=resolve})
    const manifestRoute=async route=>{await gate;await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'検証用リプレイエラー'})})}
    await page.route('**/tricks/replay/261009',manifestRoute)
    await page.getByRole('button',{name:'リプレイモード',exact:true}).click()
    const status=page.locator('[data-tricks-header-status]')
    await page.locator('[data-tricks-header-status-item="loading"]').waitFor()
    assert((await status.textContent()).includes('リプレイモード表示中（解除） | 読み込み中...'),'Replay mode and loading separated by pipe')
    assert(await page.getByText('読み込み中...', {exact:true}).count()===1,'Only header contains loading text')
    assert(await page.getByRole('button',{name:'リプレイを終了',exact:true}).count()===1,'Only nav icon, no fallback exit button')
    const nav=await page.locator('.tricks-top-bar').boundingBox()
    const sb=await status.boundingBox()
    assert(sb.x+sb.width>=nav.x+nav.width-20,'Status at far right of header')
    release()
    await page.locator('[data-tricks-header-status] [role="alert"]').waitFor()
    assert((await status.textContent()).includes('リプレイモード表示中（解除） | 検証用リプレイエラー'),'Replay initial error in header')
    assert(await page.getByText('検証用リプレイエラー',{exact:true}).count()===1,'Error has no body duplicate')
    await page.getByRole('link',{name:'リプレイモードを解除',exact:true}).click()
    await results.waitFor()
    await page.unroute('**/tricks/replay/261009',manifestRoute)
    await page.getByRole('button',{name:'リプレイモード',exact:true}).click()
    await page.locator('[data-tricks-replay-root][aria-busy="false"]').waitFor()
    await page.getByRole('button',{name:'観戦モード',exact:true}).click()
    assert((await status.textContent()).includes('リプレイモード表示中（解除） | 観戦モードで表示中（解除）'),'Both modes separated by pipe')
    await page.getByRole('link',{name:'観戦モードを解除',exact:true}).click()
    assert(await page.locator('[data-tricks-replay-root]').count()===1,'Spectator exit retains replay')
    const errorRoute=route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'検証用スナップショットエラー'})})
    await page.route('**/tricks/replay/261009/snapshot?**',errorRoute)
    await page.getByRole('button',{name:'次のコマ',exact:true}).click()
    await page.getByText('検証用スナップショットエラー',{exact:true}).waitFor()
    assert(await status.getByText('検証用スナップショットエラー',{exact:true}).count()===1,'Snapshot error in header')
    assert(await page.locator('[data-tricks-replay-seekbar]').getByText(/読み込み中/).count()===0,'No seek-box loading label')
    await page.setViewportSize({width:390,height:844})
    const exit=page.getByRole('link',{name:'リプレイモードを解除',exact:true})
    const exitBounds=await exit.boundingBox()
    const mobileHeader=await page.locator('.tricks-top-bar').boundingBox()
    const playerHeader=await page.locator('[data-tricks-header-scroll]').boundingBox()
    assert(exitBounds.x>=0&&exitBounds.x+exitBounds.width<=390,'Mobile exit link visible')
    assert(playerHeader.y>=mobileHeader.y+mobileHeader.height,'Player information clears multiline header')
    await page.screenshot({path:'next/pages/limited/tricks/output/playwright/tricks-header-error-mobile.png'})
    await exit.click()
    await page.unroute('**/tricks/replay/261009/snapshot?**',errorRoute)
    await page.setViewportSize({width:1440,height:1000})
    await results.waitFor()
    const rankRoute=route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'検証用ランキングエラー'})})
    await page.route('**/tricks/cards/*/scores**',rankRoute)
    await page.locator('[data-tricks-mini-holder-cards] button').first().click()
    await page.locator('[data-tricks-header-status] [role="alert"]').filter({hasText:'検証用ランキングエラー'}).waitFor()
    assert(await page.locator('.tricks-field-detail-panel').getByText(/読み込み中/).count()===0,'Ranking loading also moved to header')
    await page.getByRole('button',{name:'閉じる',exact:true}).click()
    await page.unroute('**/tricks/cards/*/scores**',rankRoute)
    await page.unrouteAll()
    return {checks,resultsCoverViewport:true,modeExitLinks:true,initialAndSnapshotErrorsInHeader:true,mobileHeaderClearance:true}
}
