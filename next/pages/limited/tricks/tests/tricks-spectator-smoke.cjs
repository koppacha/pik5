async (page) => {
    const assert = (value, message) => { if (!value) throw new Error(message) }
    const a = {name: 'spectator_test_a', draw_points: 5, total_rank_points: 2, card_count: 1, hand_limit: 6, take_level: 0, take_cost: 2, collected_card_count: 0}
    const b = {...a, name: 'spectator_test_b'}
    const card = (id) => ({id, event_card_id: id + 1000, stage_id: 7200 + id, title: `観戦テスト切り札${id}`, rule_name: 'テストルール', rarity: 1, difficulty: 1, stack_count: 2, limit_at: '2099-01-01T00:00:00+09:00', participant_count: 2})
    let state = {tournament: {event_id: 990401, title: '観戦UI検証', state: 'active', available: true, end_at: '2099-01-01T00:00:00+09:00', debug: true}, debug_state: {frozen: true}, server_now: '2026-10-07T12:00:00+09:00', me: a, players: [a, b], field: [card(202), card(203)], hand: [{...card(201), title: 'テスト手札'}], deck_count: 198, logs: [{id: 1, event: 'record_posted', actor_name: a.name, event_card_id: 1202, score: 100, created_at: '2026-10-07T12:00:00+09:00'}]}
    const rankings = [{post_id: 1, post_rank: 1, user_id: a.name, score: 123, rule: 1, stage_id: 7402, rps: 2, created_at: '2026-10-07T12:00:00+09:00'}, {post_id: 2, post_rank: 2, user_id: b.name, score: 111, rule: 1, stage_id: 7402, rps: 1, created_at: '2026-10-07T12:00:00+09:00'}]
    await page.route('**/api/**', async (route) => {
        const path = new URL(route.request().url()).pathname
        let json = {}
        if (path === '/api/auth/session') json = {user: {userId: a.name, role: 0}, expires: '2099-01-01T00:00:00.000Z'}
        else if (path === '/api/users') json = [{userId: a.name, name: 'テスト参加者A'}, {userId: b.name, name: 'テスト参加者B'}]
        else if (path.endsWith('/state')) json = state
        else if (path.endsWith('/scores')) json = rankings
        else if (path.endsWith('/holders')) json = {historical_counts: {}}
        await route.fulfill({json})
    })
    await page.goto('http://localhost:3005/limited/trick')
    await page.locator('[data-tricks-spectator-toggle]').waitFor()
    await page.locator('[data-tricks-player="spectator_test_a"]').waitFor()
    await page.locator('canvas').waitFor()
    await page.waitForTimeout(500)
    await page.getByRole('button', {name: '遊び方', exact: true}).click()
    await page.getByTitle('第19回期間限定ランキング 遊び方').waitFor()
    assert((await page.getByTitle('第19回期間限定ランキング 遊び方').getAttribute('src')).includes('limited_19_manual.pdf'), '当初PDF')
    await page.getByRole('button', {name: '閉じる', exact: true}).click()
    await page.getByRole('button', {name: 'ナレッジ', exact: true}).click()
    await page.locator('[role="dialog"] .markdown-content').waitFor()
    assert((await page.locator('[role="dialog"] .markdown-content').innerText()).includes('5'), 'Markdownマニュアル本文')
    assert(await page.locator('[role="dialog"] iframe').count() === 0, 'PDFを使わない')
    assert(await page.getByRole('button', {name: '編集', exact: true}).count() === 0, '静的マニュアルの編集なし')
    await page.getByRole('button', {name: '閉じる', exact: true}).click()
    await page.waitForTimeout(350)
    await page.clock.install()
    await page.clock.pauseAt(await page.evaluate(() => Date.now() + 100))
    const check = async (selector, count, message) => assert(await page.locator(selector).count() === count, message)
    await check('.tricks-dom-card-hand', 1, '通常の手札')
    await page.locator('[data-tricks-log-toggle]').click()
    assert((await page.locator('[data-tricks-log-entry]').innerText()).startsWith('10/7 12:00 -'), '通常の日時形式')
    await page.locator('[data-tricks-spectator-toggle]').click()
    await check('.tricks-command-window', 1, 'コマンド収納を維持')
    assert(await page.locator('.tricks-command-toggle').getAttribute('aria-expanded') === 'false', 'コマンド収納')
    await check('.tricks-dom-deck', 1, 'デッキスライド用DOMを維持')
    assert(await page.locator('.tricks-dom-deck').getAttribute('aria-hidden') === 'true', 'デッキ収納')
    await check('.tricks-dom-card-hand', 1, '手札スライド用DOMを維持')
    assert(await page.locator('.tricks-dom-card-hand').isDisabled(), '収納手札の操作無効')
    assert(await page.locator('[data-tricks-log-wrapper]').getAttribute('data-log-open') === 'true', 'ログ表示')
    await page.clock.runFor(300)
    assert(await page.locator('[data-tricks-log-wrapper]').evaluate(el => Math.abs(el.getBoundingClientRect().bottom - window.innerHeight) < 1), '観戦ログ右下')
    await page.locator('[data-tricks-card-id="202"]').click()
    await page.locator('.tricks-field-detail-panel').waitFor()
    const manualBounds = await page.locator('.tricks-field-detail-panel').boundingBox()
    assert(!(await page.locator('.tricks-field-detail-panel').innerText()).includes('支払記録済み'), '支払済み文言なし')
    await page.getByRole('button', {name: '閉じる', exact: true}).click()
    await check('[data-tricks-spectator-presentation]', 0, '開始前投稿の非再生')
    const post = (id, field, actor, score) => ({id, event: id === 3 ? 'record_updated' : 'record_posted', actor_name: actor, event_card_id: field, score, card_title: `切り札${field}`, created_at: '2026-10-07T12:01:00+09:00'})
    state = {...state, logs: [post(2, 1202, a.name, 123), ...state.logs], players: [{...a, card_count: 2}, {...b, draw_points: 6}]}
    await page.clock.fastForward(3100)
    await page.locator('[data-tricks-spectator-presentation="2"]').waitFor()
    await page.locator('[data-tricks-highlighted-post="2"] .user-type').waitFor()
    const autoBounds = await page.locator('.tricks-field-detail-panel').boundingBox()
    assert(Math.abs(manualBounds.x - autoBounds.x) < 1 && Math.abs(manualBounds.y - autoBounds.y) < 1, 'クリックと自動表示の位置一致')
    assert((await page.locator('.tricks-field-detail-panel').innerText()).includes('pts.'), 'pts単位')
    const duration = await page.locator('[data-tricks-highlighted-post="2"] .score-type').evaluate(el => parseFloat(getComputedStyle(el).animationDuration))
    assert(Math.abs(duration - 2 / 3) < .001, '1.5倍の点滅速度')
    assert(await page.locator('[data-tricks-highlighted-post="2"] .score-type').evaluate(el => getComputedStyle(el).animationName) === 'tricksSpectatorBlink', 'スコア点滅')
    assert(await page.locator('[data-tricks-player="spectator_test_a"]').getAttribute('data-tricks-player-blink') === 'post', '投稿者点滅')
    assert(await page.locator('[data-tricks-player="spectator_test_b"] [data-tricks-stat-blink="dp"]').count() === 1, '同時DPグリッド点滅')
    await page.locator('.tricks-field-detail-panel').evaluate(el => {el.dataset.sameModal = 'kept'})
    await page.screenshot({path: 'output/playwright/tricks-spectator-desktop.png'})
    state = {...state, logs: [post(4, 1203, a.name, 99), post(3, 1202, b.name, 111), ...state.logs]}
    await page.clock.fastForward(3100)
    assert(await page.locator('[data-tricks-player="spectator_test_b"]').getAttribute('data-tricks-player-blink') === null, '1.8秒以降の点滅解除')
    await page.clock.fastForward(6800)
    await check('[data-tricks-highlighted-post]', 1, '10秒未満点滅維持')
    await page.clock.fastForward(200)
    await check('[data-tricks-highlighted-post]', 0, '10秒後点滅終了')
    await check('[data-tricks-spectator-presentation="2"]', 1, '待機中同じモーダル')
    await page.clock.fastForward(1000)
    await page.locator('[data-tricks-spectator-presentation="3"]').waitFor()
    assert(await page.locator('.tricks-field-detail-panel').getAttribute('data-same-modal') === 'kept', '同一切り札モーダル維持')
    await page.clock.fastForward(10000)
    await check('[data-tricks-highlighted-post]', 0, '次の10秒完了')
    await page.clock.fastForward(1000)
    await page.locator('[data-tricks-spectator-presentation="4"]').waitFor()
    assert(await page.locator('[data-tricks-spectator-card]').getAttribute('data-tricks-spectator-card') === '1203', '投稿順と別切り札')
    assert(await page.locator('.tricks-field-detail-panel').getAttribute('data-same-modal') === null, '別切り札モーダル入替')
    assert(await page.locator('[data-tricks-highlighted-post="4"]').innerText() === 'テスト参加者A / 99点', '最高記録外の投稿スコア保持')
    await page.clock.fastForward(10000)
    await check('[data-tricks-spectator-presentation]', 0, '全処理後クローズ')
    const before = await page.evaluate(() => ({...window.__TRICKS_RENDER_METRICS__}))
    await page.clock.fastForward(9000)
    const after = await page.evaluate(() => ({...window.__TRICKS_RENDER_METRICS__}))
    assert(before.phaserRenderCount === after.phaserRenderCount && after.phaserLoopSleeping, '静止中Phaser再描画なし')
    state = {...state, logs: [post(6, 1203, b.name, 111), post(5, 1202, a.name, 123), ...state.logs]}
    await page.clock.fastForward(3100)
    await page.locator('[data-tricks-spectator-presentation="5"]').waitFor()
    await page.locator('[data-tricks-spectator-toggle]').click()
    await check('[data-tricks-spectator-presentation]', 0, '途中解除')
    assert(await page.locator('[data-tricks-log-wrapper]').evaluate(el => getComputedStyle(el).top) === '180px', '通常ログ位置復帰')
    await check('.tricks-dom-card-hand', 1, '手札復帰')
    await check('.tricks-command-window', 1, 'コマンド復帰')
    await page.clock.fastForward(12000)
    await check('[data-tricks-spectator-presentation]', 0, '解除後タイマー破棄')
    await page.locator('[data-tricks-spectator-toggle]').click()
    await check('[data-tricks-spectator-presentation]', 0, '再観戦のキュー初期化')
    await page.setViewportSize({width: 390, height: 844})
    await page.screenshot({path: 'output/playwright/tricks-spectator-mobile.png'})
    await page.clock.resume()
    return {passed: 'toggle, timestamp, FIFO, 10s+1s, same/different card, 1.8s cell blink, historical score, cancellation, mobile', metrics: after, canvas: await page.locator('canvas').count()}
}
